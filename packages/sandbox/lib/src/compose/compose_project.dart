import 'dart:io';
import 'dart:math';

import 'package:path/path.dart' as p;
import 'package:yaml/yaml.dart';

import 'compose_config.dart';

/// Names of compose files that are auto-discovered.
const composeFileNames = [
  'compose.yaml',
  'compose.yml',
  'docker-compose.yaml',
  'docker-compose.yml',
];

/// Name of the Dockerfile used for auto-discovery.
const dockerfileName = 'Dockerfile';

/// Random instance for generating unique project name suffixes.
final _random = Random();

/// A resolved Docker Compose project with a unique name, config file, and
/// environment variables.
///
/// [ComposeProject] handles:
/// - Auto-discovery of `compose.yaml` / `Dockerfile` in a directory
/// - Generation of a default compose config when none is found
/// - Unique project naming based on eval name, eval ID, epoch, and random suffix
class ComposeProject {
  /// Unique project name for `docker compose -p`.
  final String name;

  /// Absolute path to the resolved compose config file.
  final String configFile;

  /// Whether the config file was auto-generated (and should be cleaned up).
  final bool isAutoGenerated;

  /// Environment variables to pass to `docker compose`.
  final Map<String, String> env;

  ComposeProject._({
    required this.name,
    required this.configFile,
    required this.isAutoGenerated,
    this.env = const {},
  });

  /// Create a [ComposeProject] by resolving or generating a compose config.
  ///
  /// [name] is used as the base for the project name.
  /// [configPath] is an optional explicit compose file path. If null,
  /// auto-discovery is attempted in [searchDir].
  /// [searchDir] is the directory to search for compose files (defaults to cwd).
  /// [evalId] and [epoch] are appended to the project name for uniqueness.
  /// [env] is optional environment variables (e.g. for EVAL_METADATA_* interpolation).
  static Future<ComposeProject> create({
    required String name,
    String? configPath,
    String? searchDir,
    String? evalId,
    int? epoch,
    Map<String, String>? env,
  }) async {
    final projectName = generateProjectName(
      name,
      evalId: evalId,
      epoch: epoch,
    );

    // If explicit config provided, use it directly
    if (configPath != null) {
      final absPath = p.isAbsolute(configPath)
          ? configPath
          : p.join(searchDir ?? Directory.current.path, configPath);
      if (!File(absPath).existsSync()) {
        throw FileSystemException('Compose config not found', absPath);
      }
      return ComposeProject._(
        name: projectName,
        configFile: absPath,
        isAutoGenerated: false,
        env: env ?? const {},
      );
    }

    // Auto-discover
    final dir = searchDir ?? Directory.current.path;
    final discovered = _discoverConfigFile(dir);

    if (discovered != null) {
      return ComposeProject._(
        name: projectName,
        configFile: discovered,
        isAutoGenerated: false,
        env: env ?? const {},
      );
    }

    // Check for Dockerfile only — generate a compose config that builds it
    final dockerfile = File(p.join(dir, dockerfileName));
    if (dockerfile.existsSync()) {
      final config = ComposeConfig(
        services: {
          'default': ComposeService(
            build: '.',
            init: true,
            command: 'tail -f /dev/null',
          ),
        },
      );
      final tempFile = await _writeTempComposeFile(config, projectName);
      return ComposeProject._(
        name: projectName,
        configFile: tempFile,
        isAutoGenerated: true,
        env: env ?? const {},
      );
    }

    // No config at all — generate default
    final config = ComposeConfig.defaultConfig();
    final tempFile = await _writeTempComposeFile(config, projectName);
    return ComposeProject._(
      name: projectName,
      configFile: tempFile,
      isAutoGenerated: true,
      env: env ?? const {},
    );
  }

  /// Create a [ComposeProject] from a programmatic [ComposeConfig].
  static Future<ComposeProject> fromConfig({
    required String name,
    required ComposeConfig config,
    String? evalId,
    int? epoch,
    Map<String, String>? env,
  }) async {
    final projectName = generateProjectName(
      name,
      evalId: evalId,
      epoch: epoch,
    );
    final tempFile = await _writeTempComposeFile(config, projectName);
    return ComposeProject._(
      name: projectName,
      configFile: tempFile,
      isAutoGenerated: true,
      env: env ?? const {},
    );
  }

  /// Generates a unique, Docker-compatible project name.
  ///
  /// The name follows the pattern `devals-{name}-{evalId}-{epoch}-{random}`,
  /// sanitized to lowercase alphanumeric characters and hyphens to conform
  /// to Docker Compose project name rules. The random suffix prevents
  /// collisions when multiple isolates create sessions concurrently.
  static String generateProjectName(
    String name, {
    String? evalId,
    int? epoch,
  }) {
    final parts = ['devals', _sanitize(name)];
    if (evalId != null) parts.add(_sanitize(evalId));
    if (epoch != null) parts.add('e$epoch');
    parts.add(_randomSuffix());
    return parts.join('-');
  }

  /// Generate a 6-character random alphanumeric suffix.
  static String _randomSuffix() {
    const chars = 'abcdefghijklmnopqrstuvwxyz0123456789';
    return List.generate(6, (_) => chars[_random.nextInt(chars.length)]).join();
  }

  /// Parse the services from the compose config file.
  Future<Map<String, Map<String, Object?>>> parseServices() async {
    final content = await File(configFile).readAsString();
    final yaml = loadYaml(content);
    if (yaml is! YamlMap) return {};
    final services = yaml['services'];
    if (services is! YamlMap) return {};
    return {
      for (final entry in services.entries)
        entry.key.toString(): _yamlToMap(entry.value),
    };
  }

  /// Clean up auto-generated temp files.
  Future<void> cleanup() async {
    if (isAutoGenerated) {
      final file = File(configFile);
      if (await file.exists()) {
        await file.delete();
      }
    }
  }

  /// Determine the default service name from the project's services.
  ///
  /// Priority:
  /// 1. A service named `default`
  /// 2. A service with `x-default: true`
  /// 3. The first service listed
  static String resolveDefaultService(
    Map<String, Map<String, Object?>> services,
  ) {
    if (services.containsKey('default')) return 'default';
    for (final entry in services.entries) {
      if (entry.value['x-default'] == true) return entry.key;
    }
    return services.keys.first;
  }

  // -- Private helpers --

  static String? _discoverConfigFile(String dir) {
    for (final name in composeFileNames) {
      final file = File(p.join(dir, name));
      if (file.existsSync()) return file.path;
    }
    return null;
  }

  static Future<String> _writeTempComposeFile(
    ComposeConfig config,
    String projectName,
  ) async {
    final tempDir = await Directory.systemTemp.createTemp('devals_sandbox_');
    final file = File(p.join(tempDir.path, 'compose.yaml'));
    await file.writeAsString(config.toYaml());
    return file.path;
  }

  static String _sanitize(String s) {
    return s
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-z0-9]'), '-')
        .replaceAll(RegExp(r'-+'), '-')
        .replaceAll(RegExp(r'^-|-$'), '');
  }
}

Map<String, Object?> _yamlToMap(dynamic value) {
  if (value is YamlMap) {
    return {
      for (final entry in value.entries)
        entry.key.toString(): _yamlToValue(entry.value),
    };
  }
  return {};
}

Object? _yamlToValue(dynamic value) {
  if (value is YamlMap) return _yamlToMap(value);
  if (value is YamlList) return value.map(_yamlToValue).toList();
  return value;
}
