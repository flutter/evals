import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:test/test.dart';
import 'package:devals_sandbox/sandbox.dart';

void main() {
  group('ComposeProject.generateProjectName', () {
    test('basic name', () {
      final name = ComposeProject.generateProjectName('my_eval');
      expect(name, startsWith('devals-my-eval-'));
    });

    test('with eval ID', () {
      final name = ComposeProject.generateProjectName(
        'my_eval',
        evalId: 'run-1',
      );
      expect(name, startsWith('devals-my-eval-run-1-'));
    });

    test('with epoch', () {
      final name = ComposeProject.generateProjectName('my_eval', epoch: 3);
      expect(name, startsWith('devals-my-eval-e3-'));
    });

    test('with eval ID and epoch', () {
      final name = ComposeProject.generateProjectName(
        'my_eval',
        evalId: 'abc',
        epoch: 2,
      );
      expect(name, startsWith('devals-my-eval-abc-e2-'));
    });

    test('sanitizes special characters', () {
      final name = ComposeProject.generateProjectName('My Eval!@#v2');
      expect(name, startsWith('devals-my-eval-v2-'));
    });

    test('collapses multiple hyphens', () {
      final name = ComposeProject.generateProjectName('a--b__c');
      expect(name, startsWith('devals-a-b-c-'));
    });

    test('generates unique names for concurrent safety', () {
      final names = List.generate(
        100,
        (_) => ComposeProject.generateProjectName('eval'),
      );
      // All names should be unique due to random suffix
      expect(names.toSet().length, equals(100));
    });
  });

  group('ComposeProject.resolveDefaultService', () {
    test('prefers service named "default"', () {
      final result = ComposeProject.resolveDefaultService({
        'worker': <String, Object?>{},
        'default': <String, Object?>{},
        'other': <String, Object?>{},
      });
      expect(result, equals('default'));
    });

    test('uses x-default: true as fallback', () {
      final result = ComposeProject.resolveDefaultService({
        'worker': <String, Object?>{},
        'agent': <String, Object?>{'x-default': true},
        'other': <String, Object?>{},
      });
      expect(result, equals('agent'));
    });

    test('uses first service as last resort', () {
      final result = ComposeProject.resolveDefaultService({
        'alpha': <String, Object?>{},
        'beta': <String, Object?>{},
      });
      expect(result, equals('alpha'));
    });
  });

  group('ComposeProject.create', () {
    late Directory tempDir;

    setUp(() async {
      tempDir = await Directory.systemTemp.createTemp('compose_project_test_');
    });

    tearDown(() async {
      if (await tempDir.exists()) {
        await tempDir.delete(recursive: true);
      }
    });

    test('auto-discovers compose.yaml', () async {
      final composeFile = File(p.join(tempDir.path, 'compose.yaml'));
      await composeFile.writeAsString('''
services:
  default:
    image: python:3.12
    init: true
    command: tail -f /dev/null
''');

      final project = await ComposeProject.create(
        name: 'test_eval',
        searchDir: tempDir.path,
      );
      expect(project.configFile, equals(composeFile.path));
      expect(project.isAutoGenerated, isFalse);
      expect(project.name, contains('devals-test-eval'));
    });

    test('auto-discovers docker-compose.yml', () async {
      final composeFile = File(p.join(tempDir.path, 'docker-compose.yml'));
      await composeFile.writeAsString('''
services:
  default:
    image: node:20
''');

      final project = await ComposeProject.create(
        name: 'test_eval',
        searchDir: tempDir.path,
      );
      expect(project.configFile, equals(composeFile.path));
      expect(project.isAutoGenerated, isFalse);
    });

    test('generates default config when nothing found', () async {
      final project = await ComposeProject.create(
        name: 'test_eval',
        searchDir: tempDir.path,
      );
      expect(project.isAutoGenerated, isTrue);
      expect(File(project.configFile).existsSync(), isTrue);

      // Verify the generated file contains flutter image
      final content = await File(project.configFile).readAsString();
      expect(content, contains('ghcr.io/cirruslabs/flutter:stable'));

      // Cleanup
      await project.cleanup();
    });

    test('generates build config when Dockerfile found', () async {
      final dockerfile = File(p.join(tempDir.path, 'Dockerfile'));
      await dockerfile.writeAsString('FROM python:3.12\n');

      final project = await ComposeProject.create(
        name: 'test_eval',
        searchDir: tempDir.path,
      );
      expect(project.isAutoGenerated, isTrue);

      final content = await File(project.configFile).readAsString();
      expect(content, contains('build'));

      await project.cleanup();
    });

    test('uses explicit config path', () async {
      final customFile = File(p.join(tempDir.path, 'custom.yaml'));
      await customFile.writeAsString('''
services:
  myservice:
    image: alpine:latest
''');

      final project = await ComposeProject.create(
        name: 'test_eval',
        configPath: customFile.path,
      );
      expect(project.configFile, equals(customFile.path));
      expect(project.isAutoGenerated, isFalse);
    });

    test('throws when explicit config not found', () async {
      expect(
        () => ComposeProject.create(
          name: 'test_eval',
          configPath: '/nonexistent/compose.yaml',
        ),
        throwsA(isA<FileSystemException>()),
      );
    });
  });

  group('ComposeProject.parseServices', () {
    test('parses services from YAML', () async {
      final tempDir = await Directory.systemTemp.createTemp(
        'parse_services_test_',
      );
      final composeFile = File(p.join(tempDir.path, 'compose.yaml'));
      await composeFile.writeAsString('''
services:
  default:
    image: python:3.12
    init: true
  worker:
    image: node:20
    x-local: true
''');

      final project = await ComposeProject.create(
        name: 'test_eval',
        searchDir: tempDir.path,
      );

      final services = await project.parseServices();
      expect(services, hasLength(2));
      expect(services.containsKey('default'), isTrue);
      expect(services.containsKey('worker'), isTrue);
      expect(services['default']!['image'], equals('python:3.12'));
      expect(services['worker']!['x-local'], isTrue);

      await tempDir.delete(recursive: true);
    });
  });

  group('ComposeProject.fromConfig', () {
    test('creates project from programmatic config', () async {
      final config = ComposeConfig(
        services: {
          'default': ComposeService(
            image: 'python:3.12',
            init: true,
            command: 'tail -f /dev/null',
          ),
        },
      );

      final project = await ComposeProject.fromConfig(
        name: 'prog_eval',
        config: config,
        evalId: 'e1',
        epoch: 1,
      );

      expect(project.isAutoGenerated, isTrue);
      expect(project.name, contains('devals-prog-eval'));
      expect(project.name, contains('e1'));

      final content = await File(project.configFile).readAsString();
      expect(content, contains('python:3.12'));

      await project.cleanup();
    });
  });
}
